export const LOGIC_QUESTION_RULES = `
【逻辑推理题 logic_reasoning — 必须严谨】
1. 必须提供 options 数组（2-4 个选项），answer 为唯一正确选项的下标（从 0 开始）
2. 题干中的条件必须能**严格推出唯一答案**，禁止模棱两可
3. 排序/比身高类题目：条件必须能确定**完整顺序**或**唯一的最值**
   - ✅ 正确：「小明比小红高，小红比小刚高，谁最高？」→ 唯一答案：小明
   - ✅ 正确：「甲比乙高，甲比丙也高，谁最高？」→ 唯一答案：甲
   - ❌ 错误：「小明比小红高，小红比小刚矮，谁最高？」→ 只能推出小明和小刚都比小红高，无法比较小明和小刚，**禁止出这种题**
4. 若问「谁最高/谁最矮」，必须保证只有一个选项满足
5. 条件数量要够：3 人比身高时，至少需要能连起来比较的信息（如 A>B 且 B>C，或 A>B 且 A>C 且 B>C）
6. 题干只写题目，不要写 (1=甲 2=乙) 编号；不要用人名充当 unit`;

